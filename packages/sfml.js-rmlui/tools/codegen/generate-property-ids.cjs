'use strict';

const fs = require('node:fs');
const path = require('node:path');
const {
  describe, words, fieldLabel, sentinelDescription,
} = require('./documentation.cjs');

const root = path.join(__dirname, '../..');
const header = fs.readFileSync(path.join(root,
  'vendor/rmlui/Include/RmlUi/Core/ID.h'), 'utf8')
  .replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
const source = fs.readFileSync(path.join(root,
  'vendor/rmlui/Source/Core/StyleSheetSpecification.cpp'), 'utf8');
const properties = new Map([ ...source.matchAll(
  new RegExp('RegisterProperty\\(PropertyId::(\\w+), "([^"]+)", ' +
    '"([^"]*)", (true|false), (true|false)\\)', 'g')
) ].map(([ , name, css, defaultValue, inherited, layout ]) =>
  [ name, { css, defaultValue, inherited, layout }]));
const shorthands = new Map([ ...source.matchAll(
  /RegisterShorthand\(ShorthandId::(\w+), "([^"]+)", "([^"]+)"/g
) ].map(([ , name, css, expands ]) => [ name, { css, expands }]));
const localDescriptions = Object.fromEntries(Object.entries({
  AspectRatio: 'viewport width-to-height ratio|视口宽高比|ビューポートの縦横比|뷰포트 너비 대 ' +
    '높이 비율',
  MinAspectRatio: 'minimum viewport width-to-height ratio|视口最小宽高比|' +
    'ビューポートの最小縦横比|뷰포트 최소 너비 대 높이 비율',
  MaxAspectRatio: 'maximum viewport width-to-height ratio|视口最大宽高比|' +
    'ビューポートの最大縦横比|뷰포트 최대 너비 대 높이 비율',
  Resolution: 'display density in dots per pixel|显示密度（每像素点数）|ピクセル当たりの表示密度|' +
    '픽셀당 표시 밀도',
  MinResolution: 'minimum display density|最小显示密度|最小表示密度|최소 표시 밀도',
  MaxResolution: 'maximum display density|最大显示密度|最大表示密度|최대 표시 밀도',
  Orientation: 'portrait or landscape viewport orientation|视口横向或纵向方向|' +
    'ビューポートの縦向き・横向き|뷰포트 세로 또는 가로 방향',
  Theme: 'active named theme|当前具名主题|現在の名前付きテーマ|현재 이름 지정 테마',
  Src: 'font file source|字体文件来源|フォントファイルの参照元|글꼴 파일 소스',
  FallbackFace: 'whether to register the font as a fallback face|' +
    '是否将字体注册为回退字体|代替フォントとして登録するか|대체 글꼴로 등록할지 여부',
  FaceIndex: 'face index within a font collection|字体集合内的字体索引|' +
    'フォント集合内のフェイス番号|글꼴 모음 안의 글꼴 인덱스',
}).map(([ name, text ]) => [ name, words(text) ]));

const specifications = [
  {
    enumName: 'PropertyId', filename: 'property-ids.ts', expected: 103,
    description: words('Identifiers for built-in and custom RCSS properties.|' +
      '内置和自定义 RCSS 属性的标识。|' +
      '組み込みと独自の RCSS プロパティの識別子。|' +
      '내장 및 사용자 정의 RCSS 속성의 식별자입니다.'),
  },
  {
    enumName: 'ShorthandId', filename: 'shorthand-ids.ts', expected: 24,
    description: words('Identifiers for RCSS shorthand property groups.|' +
      'RCSS 简写属性组的标识。|RCSS 短縮形プロパティ群の識別子。|' +
      'RCSS 단축 속성 그룹의 식별자입니다.'),
  },
  {
    enumName: 'MediaQueryId', filename: 'media-query-ids.ts', expected: 16,
    description: words('Identifiers for context-dependent media conditions.|' +
      '依上下文判断的媒体查询条件标识。|' +
      'コンテキストに応じて評価するメディア条件の識別子。|' +
      '컨텍스트에 따라 평가하는 미디어 조건의 식별자입니다.'),
  },
  {
    enumName: 'FontFaceId', filename: 'font-face-ids.ts', expected: 8,
    description: words('Identifiers for descriptors in a font-face rule.|' +
      '字体声明规则中描述项的标识。|フォント宣言規則の記述子の識別子。|' +
      '글꼴 선언 규칙 설명자의 식별자입니다.'),
  },
];

for (const specification of specifications) {
  const { enumName, filename, expected } = specification;
  const body = header.match(
    new RegExp(`enum class ${enumName}[^{}]+\\{([^}]+)\\}`)
  )?.[1];
  if (!body) {
    throw new Error(`Missing RmlUi ${enumName} declaration`);
  }

  const entries = [ ...body.matchAll(
    /\b(\w+)\s*(?:=\s*(\w+))?\s*(?:,|$)/g
  ) ];
  if (entries.length !== expected) {
    throw new Error(
      `Review ${enumName}: expected ${expected}, got ${entries.length}`);
  }

  const output = [
    '// Generated from RmlUi 6.3 Core/ID.h.',
    '// Generated by tools/codegen/generate-property-ids.cjs.',
    '',
    ...describe(specification.description),
    `export enum ${enumName} {`,
  ];
  const values = new Map();
  let previous = -1;

  for (const [ , name, expression ] of entries) {
    const value = expression === undefined
      ? previous + 1 : values.get(expression) ?? Number(expression);
    if (!Number.isInteger(value)) {
      throw new Error(`Unrecognized ${enumName} expression: ${expression}`);
    }

    values.set(name, value);
    previous = value;
    let description = sentinelDescription(name, value);
    const extra = [];
    if (!description) {
      const property = properties.get(name);
      const shorthand = shorthands.get(name);
      const label = localDescriptions[name] ?? fieldLabel(name);
      description = label.map((text, i) => [
        `Identifier for ${text}.`, `${text}的标识。`,
        `${text}の識別子。`, `${text} 식별자입니다.`,
      ][i]);
      if (enumName === 'PropertyId') {
        if (!property) {
          throw new Error(`Missing property registration: ${name}`);
        }
        extra.push(
          `@default \`${property.defaultValue}\``,
          `@remarks RCSS: \`${property.css}\`. Inherited: ${
            property.inherited}. Forces layout: ${property.layout}.`,
          `@zh RCSS：\`${property.css}\`。是否继承：${
            property.inherited}。是否触发布局：${property.layout}。`,
          `@ja RCSS：\`${property.css}\`。継承：${
            property.inherited}。レイアウト更新：${property.layout}。`,
          `@ko RCSS: \`${property.css}\`. 상속: ${
            property.inherited}. 레이아웃 갱신: ${property.layout}.`
        );
      } else if (enumName === 'ShorthandId') {
        if (!shorthand) {
          throw new Error(`Missing shorthand registration: ${name}`);
        }
        extra.push(
          `@remarks \`${shorthand.css}\` expands: ${shorthand.expands}.`,
          `@zh \`${shorthand.css}\` 展开为：${shorthand.expands}。`,
          `@ja \`${shorthand.css}\` の展開先：${shorthand.expands}。`,
          `@ko \`${shorthand.css}\` 확장 대상: ${shorthand.expands}.`
        );
      }
    }
    output.push(...describe(description, '  ', extra),
      `  ${name} = ${values.has(expression) ? expression : value},`);
  }

  output.push('}', '');
  const destination = path.join(root, 'src/generated', filename);
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  const content = output.join('\n');

  if (!fs.existsSync(destination) ||
    fs.readFileSync(destination, 'utf8') !== content) {
    fs.writeFileSync(destination, content);
  }
}
